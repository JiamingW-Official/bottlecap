// ── Utility helpers ────────────────────────────────────────────────────

export type MaterialCategory = MaterialEntry['category'];

export const MATERIAL_CATEGORIES: MaterialCategory[] = [
  'Metals',
  'Plastics',
  'Textiles',
  'Composites',
  'Natural',
  'Ceramics',
] as const;

export function getMaterialsByCategory(category: MaterialCategory): MaterialEntry[] {
  return MATERIALS_DATABASE.filter((m) => m.category === category);
}

export function searchMaterials(query: string): MaterialEntry[] {
  const q = query.toLowerCase();
  return MATERIALS_DATABASE.filter(
    (m) =>
      m.name.toLowerCase().includes(q) ||
      m.category.toLowerCase().includes(q) ||
      m.properties.some((p) => p.toLowerCase().includes(q)) ||
      m.commonUses.some((u) => u.toLowerCase().includes(q))
  );
}

export function getSustainableMaterials(): MaterialEntry[] {
  return MATERIALS_DATABASE.filter((m) => m.sustainability === 'High');
}

export function getRecyclableMaterials(): MaterialEntry[] {
  return MATERIALS_DATABASE.filter((m) => m.recyclable);
}

export function getMaterialCostRange(name: string): { min: number; max: number } | undefined {
  const material = MATERIALS_DATABASE.find(
    (m) => m.name.toLowerCase() === name.toLowerCase()
  );
  return material?.costPerKg;
}
