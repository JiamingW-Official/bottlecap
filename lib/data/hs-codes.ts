// ── Utility helpers ────────────────────────────────────────────────────

export const HS_CATEGORIES = Array.from(
  new Set(HS_CODES.map((c) => c.category))
);

export function getHsCodesByCategory(category: string): HsCodeEntry[] {
  return HS_CODES.filter((c) => c.category === category);
}

export function searchHsCodes(query: string): HsCodeEntry[] {
  const q = query.toLowerCase();
  return HS_CODES.filter(
    (c) =>
      c.code.includes(q) ||
      c.description.toLowerCase().includes(q) ||
      c.examples.some((ex) => ex.toLowerCase().includes(q))
  );
}

export function getEffectiveTariff(entry: HsCodeEntry, fromChina: boolean): number {
  return fromChina ? entry.usRate + entry.chinaRate : entry.usRate;
}
