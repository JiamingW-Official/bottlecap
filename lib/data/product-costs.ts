// ── Utility helpers ────────────────────────────────────────────────────

export function getProductBySlug(slug: string): ProductCostEntry | undefined {
  return PRODUCT_COSTS.find((p) => p.slug === slug);
}

export function searchProducts(query: string): ProductCostEntry[] {
  const q = query.toLowerCase();
  return PRODUCT_COSTS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.slug.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.materials.some((m) => m.toLowerCase().includes(q))
  );
}

export function getProductsByCategory(category: string): ProductCostEntry[] {
  return PRODUCT_COSTS.filter(
    (p) => p.category.toLowerCase() === category.toLowerCase()
  );
}
